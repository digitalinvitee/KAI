/**
 * Small deterministic PRNG so mock data is identical on every visit:
 * the same date always produces the same fictional bookings.
 */

export const hashString = (value) => {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
};

export const createRandom = (seed) => {
  let state = typeof seed === 'number' ? seed >>> 0 : hashString(String(seed));
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };

  return {
    next,
    between: (min, max) => min + next() * (max - min),
    int: (min, max) => Math.floor(min + next() * (max - min + 1)),
    pick: (items) => items[Math.floor(next() * items.length)],
    weighted: (entries) => {
      const total = entries.reduce((sum, [, weight]) => sum + weight, 0);
      let roll = next() * total;
      for (const [value, weight] of entries) {
        roll -= weight;
        if (roll <= 0) return value;
      }
      return entries[entries.length - 1][0];
    },
  };
};

const REFERENCE_ALPHABET = 'ACDEFGHJKLMNPQRTUVWXY34679';

export const referenceCode = (random, length = 3) =>
  Array.from({ length }, () => REFERENCE_ALPHABET[Math.floor(random.next() * REFERENCE_ALPHABET.length)]).join('');
